# =====================================================================
# 🛠️ STEP 1: `yield` কীভাবে কাজ করে? (Next মেকানিজম)
# =====================================================================
# সাধারণ ফাংশনে return করার পর তার ভেতরের ভ্যারিয়েবল সব ডিলিট হয়ে যায়।
# কিন্তু yield করলে পাইথন ফাংশনের ঐ লাইনের স্টেট (অবস্থা) মেমরিতে সেভ করে রাখে।

def simple_generator():
    yield "First Value 🥇"
    yield "Second Value 🥈"
    yield "Third Value 🥉"

# জেনারেটর অবজেক্ট তৈরি করা:
gen = simple_generator()

print(next(gen))  # 👉 Output: First Value 🥇 (১ম yield পর্যন্ত রান হয়ে পজ হবে)
print(next(gen))  # 👉 Output: Second Value 🥈 (২য় yield পর্যন্ত রান হয়ে পজ হবে)
print(next(gen))  # 👉 Output: Third Value 🥉 (৩য় yield পর্যন্ত রান হয়ে পজ হবে)

# ⚠️ 注意: আমরা যদি এখন আবার `print(next(gen))` কল করি, 
# তাহলে পাইথন 'StopIteration' এরর থ্রো করবে, কারণ ডেটা শেষ!


# =====================================================================
# 🚀 STEP 2: লুপ দিয়ে জেনারেটর হ্যান্ডেল করা (সবচেয়ে সেফ পদ্ধতি)
# =====================================================================
# বাস্তব জীবনে আমরা `next()` বারবার না লিখে `for` লুপ ব্যবহার করি। 
# `for` লুপ ব্যাকহ্যান্ডে নিজে থেকেই `next()` কল করে এবং ডেটা শেষ হলে এরর আসতে দেয় না।

def square_generator():
    n = 1
    while n <= 5:
        sq = n * n
        yield sq  # ভ্যালুটা বাইরে পাঠিয়ে দিয়ে ফাংশনটি এখানে ওয়েট করবে
        n += 1    # পরের বার যখন কল হবে, কোড এখান থেকে রিজিউম (শুরু) হবে

# লুপ চালিয়ে ডেটা রিড করা:
for value in square_generator():
    print(f"Square: {value}")


# =====================================================================
# 🔥 STEP 3: Generator Comprehension (১ লাইনে জেনারেটর তৈরি)
# =====================================================================
# লিস্ট কমপ্রিহেনশনে থার্ড ব্র্যাকেট `[]` ব্যবহার করা হয় যা পুরো লিস্ট মেমরিতে লোড করে।
# কিন্তু ফার্স্ট ব্র্যাকেট `()` ব্যবহার করলে সেটি একটি জেনারেটর তৈরি করে, যা মেমরি বাঁচায়।

# (A) List Comprehension (মেমরি খাদক ❌):
list_comp = [x * x for x in range(1, 6)]
print(type(list_comp), list_comp)  # 👉 Output: <class 'list'> [1, 4, 9, 16, 25]

# (B) Generator Comprehension (স্মার্ট ও লাইটওয়েট ✅):
gen_comp = (x * x for x in range(1, 6))
print(type(gen_comp))  # 👉 Output: <class 'generator'>

# জেনারেটর কমপ্রিহেনশন থেকে ভ্যালু বের করার নিয়ম:
for item in gen_comp:
    print(f"Gen Item: {item}")


# =====================================================================
# 👑 STEP 4: কেন জেনারেটর ব্যবহার করবেন? (Real-World Power)
# =====================================================================
# ধরুন আপনার কাছে ১ কোটি ডেটা আছে। লিস্ট আকারে আনলে র‍্যাম (RAM) ক্র্যাশ করবে।
# কিন্তু জেনারেটর দিয়ে এক কোটি ডেটা প্রসেস করলেও ১টি ভ্যালুর সমান মেমরি খরচ হবে।

def big_range_generator(limit):
    num = 0
    while num < limit:
        yield num
        num += 1

# আমরা এখানে ১ কোটি পর্যন্ত রেঞ্জ সেট করলাম, কিন্তু মেমরি খরচ হবে প্রায় জিরো!
huge_data = big_range_generator(10000000)

print(next(huge_data))  # 👉 0
print(next(huge_data))  # 👉 1
