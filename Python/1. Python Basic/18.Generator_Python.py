# 💡 জেনারেটর বোঝার ৩টি গোল্ডেন রুল:
# ১. `return` ফাংশনকে চিরতরে শেষ করে দেয়, কিন্তু `yield` ফাংশনকে সাময়িক পজ (Pause) করে।
# ২. জেনারেটর ফাংশন কল করলে সরাসরি কোনো ভ্যালু দেয় না, বরং একটি 'Generator Object' দেয়।
# ৩. `next()` ফাংশন দিয়ে জেনারেটর থেকে এক এক করে ভ্যালু টেনে বের করতে হয়।
